package com.merseyside.jobs.hold

import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.emptyFlow

/**
 * Просьба к системе не убивать процесс, пока идёт работа.
 *
 * У платформ это разные вещи, и одинаковыми они не станут: на Android —
 * сервис на переднем плане, на iOS — отсрочка засыпания, в браузере —
 * ничего. Общего у них ровно два действия: взять удержание и отпустить.
 */
interface ProcessHold {

    /** Вызывается, когда появилась первая работающая задача. */
    suspend fun acquire()

    /** Вызывается, когда работающих задач не осталось. */
    suspend fun release()

    /**
     * Система забирает время назад — работу нужно свернуть прямо сейчас.
     *
     * Так делает iOS, когда отсрочка засыпания подходит к концу. Рантайм на
     * это отменяет задачи: пройденные шаги уже в хранилище, и после возвращения
     * в приложение работа продолжится с ближайшего непройденного.
     */
    val expirations: Flow<Unit>
        get() = emptyFlow()
}

/**
 * Удержание, которое ничего не удерживает.
 *
 * Для браузера, где сроком жизни вкладки распоряжаться нельзя, и для случаев,
 * когда фоновая работа приложению не нужна вовсе.
 */
object NoProcessHold : ProcessHold {

    override suspend fun acquire() = Unit

    override suspend fun release() = Unit
}
