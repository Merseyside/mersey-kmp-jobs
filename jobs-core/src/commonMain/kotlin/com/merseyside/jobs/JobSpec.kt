package com.merseyside.jobs

import kotlinx.serialization.KSerializer

/**
 * Описание вида работы: что за задача и как её выполнять.
 *
 * Одно на тип, а не на запуск. Регистрируется при создании [JobRunner] —
 * именно по [type] незавершённая работа воссоздаётся после перезапуска
 * приложения, когда исходной лямбды в памяти уже нет.
 */
interface JobSpec<P : Any, R : Any> {

    /**
     * Постоянное имя вида работы. Попадает в хранилище, поэтому переименование
     * равнозначно потере сохранённого прогресса всех задач этого вида.
     */
    val type: String

    /** Параметры уходят в хранилище, чтобы задачу можно было завести заново. */
    val paramsSerializer: KSerializer<P>

    suspend fun JobScope.execute(params: P): R

    /**
     * Стоит ли повторять работу после этой ошибки.
     *
     * Ошибки бывают двух родов, и различить их может только сама работа:
     * рантайм чужих исключений не знает. «Нет сети», «слишком часто», «сервис
     * молчит» — временные, работу нужно повторить позже, и для того, кто её
     * ждёт, ничего не случилось. «Нет прав», «ключ не тот», «плейлиста больше
     * нет» — окончательные: сколько ни повторяй, ответ будет тем же, и человеку
     * нужно сказать об этом сразу.
     *
     * По умолчанию не повторяем ничего: молча тикать в пустоту хуже, чем честно
     * признать неудачу.
     */
    fun isRetryable(error: Throwable): Boolean = false
}
